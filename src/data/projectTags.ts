export const getProjectTagStyle = (tag: string) => projectTagStyles[tag] ?? fallbackProjectTagStyle;

export const getProjectTagRenderGroups = (projectTags: ProjectTags): ProjectTagRenderGroup[] =>
	projectTagGroupOrder
		.map((group) => ({
			group,
			tags: (projectTags[group] ?? []).map((label) => ({
				label,
				style: getProjectTagStyle(label),
			})),
		}))
		.filter((group) => group.tags.length > 0);

export const getProjectTagStyleVars = (style: ProjectTagStyle) =>
	`--tag-bg: ${style.background}; --tag-text: ${style.text}; --tag-border: ${style.border}; --tag-dark-bg: ${style.darkBackground}; --tag-dark-text: ${style.darkText}; --tag-dark-border: ${style.darkBorder};`;
